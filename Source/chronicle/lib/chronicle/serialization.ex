defmodule Chronicle.Serialization do
  @moduledoc """
  Encodes event and read model structs to Chronicle's JSON wire format and decodes them back.

  This is the single place where the client decides how a struct travels over the wire, so
  the JSON schema generated by `Chronicle.Schemas.JsonSchemaGenerator` and the payload that is
  sent can never drift apart.

  ## Key styles

    * `:camel` — struct field names are rendered as `camelCase` at **every depth** (events).
    * `:identity` — struct field names are kept as-is (read models).

  Keys of plain maps are **data**, not field names, and are never transformed.

  ## Value rules

    * A `Chronicle.Concept` is written as its wrapped value.
    * Nested structs (and structs inside lists and maps) are written field by field.
    * `DateTime`, `NaiveDateTime`, `Date` and `Time` are written as ISO 8601 strings.
    * `MapSet` is written as a list; non-boolean atoms are written as strings.

  ## Decoding

  Decoding is guided by the struct's defaults: a nested struct default decodes the nested
  object into that struct, a concept default re-wraps the value, a date default parses the
  string. An integer default receives an integer when the kernel returned a whole-number
  float (`160.0` becomes `160`). Fields that hold a list of structs, or a struct that defaults
  to `nil`, are declared with the optional `types:` option of `use Chronicle.Events.EventType`
  and `use Chronicle.ReadModels.ReadModel`:

      use Chronicle.Events.EventType,
        id: "order-placed",
        types: [lines: {:list, MyApp.OrderLine}, address: MyApp.Address, labels: :map]
  """

  @opaque_structs [DateTime, NaiveDateTime, Date, Time]

  @type style :: :camel | :identity

  @doc "Encodes a struct (or any term) to a JSON string."
  @spec to_json(term(), style()) :: String.t()
  def to_json(term, style \\ :camel), do: term |> encode(style) |> Jason.encode!()

  @doc "Converts a struct (or any term) to a JSON-encodable term using `style` for field names."
  @spec encode(term(), style()) :: term()
  def encode(term, style \\ :camel)

  def encode(%module{} = struct, style) do
    cond do
      module in @opaque_structs ->
        struct

      concept?(module) ->
        encode(struct.value, style)

      match?(%MapSet{}, struct) ->
        struct |> MapSet.to_list() |> encode(style)

      true ->
        struct
        |> Map.from_struct()
        |> Map.new(fn {key, value} -> {wire_key(key, style), encode(value, style)} end)
    end
  end

  def encode(map, style) when is_map(map),
    do: Map.new(map, fn {key, value} -> {to_string(key), encode(value, style)} end)

  def encode(list, style) when is_list(list), do: Enum.map(list, &encode(&1, style))
  def encode(nil, _style), do: nil
  def encode(bool, _style) when is_boolean(bool), do: bool
  def encode(atom, _style) when is_atom(atom), do: Atom.to_string(atom)
  def encode(other, _style), do: other

  @doc """
  Decodes a JSON string or an already decoded map into `module`.

  Unknown keys are ignored. Returns the struct, or `nil` when the JSON is invalid.
  """
  @spec decode(module(), String.t() | map(), style()) :: struct() | nil
  def decode(module, json, style \\ :camel)

  def decode(module, json, style) when is_binary(json) do
    case Jason.decode(json) do
      {:ok, data} when is_map(data) -> decode(module, data, style)
      _ -> nil
    end
  end

  def decode(module, data, style) when is_map(data) do
    defaults = module.__struct__()
    types = field_types(module)
    lookup = field_lookup(defaults)

    fields =
      Enum.flat_map(data, fn {key, value} ->
        case Map.fetch(lookup, normalize_key(key)) do
          {:ok, field} ->
            [{field, cast(value, Map.get(types, field), Map.fetch!(defaults, field), style)}]

          :error ->
            []
        end
      end)

    struct(module, fields)
  end

  @doc "Returns the declared field type hints of a struct module (see the moduledoc)."
  @spec field_types(module()) :: %{atom() => term()}
  def field_types(module) do
    if Code.ensure_loaded?(module) and function_exported?(module, :__chronicle_field_types__, 0),
      do: Map.new(module.__chronicle_field_types__()),
      else: %{}
  end

  @doc "Renders a struct field name using `style`."
  @spec wire_key(atom() | String.t(), style()) :: String.t()
  def wire_key(key, :identity), do: to_string(key)

  def wire_key(key, :camel) do
    [head | tail] = key |> to_string() |> String.split("_")
    head <> Enum.map_join(tail, &String.capitalize/1)
  end

  @doc "Converts `camelCase`/`PascalCase` to `snake_case`."
  @spec snake_case(String.t()) :: String.t()
  def snake_case(name) do
    name
    |> String.replace(~r/(?<=[a-z0-9])([A-Z])/, "_\\1")
    |> String.downcase()
  end

  # --- decoding helpers -------------------------------------------------------------------

  defp field_lookup(defaults) do
    defaults
    |> Map.from_struct()
    |> Map.new(fn {field, _} -> {Atom.to_string(field), field} end)
  end

  defp normalize_key(key) when is_binary(key), do: snake_case(key)
  defp normalize_key(key), do: key |> to_string() |> snake_case()

  defp cast(nil, _type, _default, _style), do: nil

  defp cast(value, {:list, module}, _default, style) when is_list(value) and is_atom(module),
    do: Enum.map(value, &cast_into(&1, module, style))

  defp cast(value, :map, _default, _style), do: value

  defp cast(value, module, _default, style)
       when is_atom(module) and not is_nil(module) and is_map(value),
       do: cast_into(value, module, style)

  defp cast(value, _type, %module{} = default, style) do
    cond do
      module in [DateTime] and is_binary(value) ->
        case DateTime.from_iso8601(value) do
          {:ok, dt, _} -> dt
          _ -> value
        end

      module == NaiveDateTime and is_binary(value) ->
        parse(NaiveDateTime.from_iso8601(value), value)

      module == Date and is_binary(value) ->
        parse(Date.from_iso8601(value), value)

      module == Time and is_binary(value) ->
        parse(Time.from_iso8601(value), value)

      concept?(module) ->
        struct(module, value: cast(value, nil, default.value, style))

      module in @opaque_structs ->
        value

      is_map(value) ->
        decode(module, value, style)

      true ->
        value
    end
  end

  defp cast(value, _type, default, _style) when is_integer(default) and is_float(value) do
    if value == Float.round(value), do: trunc(value), else: value
  end

  defp cast(value, _type, _default, _style), do: value

  defp cast_into(value, module, style) when is_map(value) do
    if function_exported?(module, :__struct__, 0), do: decode(module, value, style), else: value
  end

  defp cast_into(value, _module, _style), do: value

  defp parse({:ok, result}, _fallback), do: result
  defp parse(_error, fallback), do: fallback

  defp concept?(module) do
    Code.ensure_loaded?(module) and function_exported?(module, :__chronicle_concept__, 1)
  end
end
